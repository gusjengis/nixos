#!/usr/bin/env python3
"""Run on Mac: capture every UI/Chrome color exposed by ThemeSource.

Uses isolated temporary profiles. Never reads or changes the user's profile.
Headless WebContents colors are evidence for that provider key, not proof of
native window materials or the currently open browser's custom theme.
"""
import argparse
import datetime
import hashlib
import html
import json
from pathlib import Path
import re
import subprocess
import tempfile

CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"


def capture(mode, high_contrast=False, incognito=False, seed=None):
    with tempfile.TemporaryDirectory(prefix="opencode-chrome-colors-") as folder:
        profile = Path(folder) / "Default"
        profile.mkdir()
        (profile / "Preferences").write_text(json.dumps({
            "browser": {"theme": {"color_scheme2": 2 if mode == "dark" else 1}}
        }))
        command = [CHROME, "--headless", "--no-first-run", "--no-default-browser-check",
                   "--disable-background-networking", "--allow-chrome-scheme-url",
                   f"--user-data-dir={folder}", "--dump-dom"]
        if mode == "dark":
            command.append("--force-dark-mode")
        if high_contrast:
            command.append("--force-high-contrast")
        if incognito:
            command.append("--incognito")
        if seed is not None:
            command.append(f"--install-autogenerated-theme={seed}")
        command.append("chrome://theme/colors.css?sets=ui,chrome")
        result = subprocess.run(command, capture_output=True, text=True, timeout=60, check=True)
        pre = re.search(r"<pre[^>]*>(.*?)</pre>", result.stdout, re.S)
        if not pre:
            raise RuntimeError(f"No ThemeSource CSS in response: {result.stdout[:300]}")
        css = html.unescape(pre.group(1))
        tokens = dict(re.findall(r"(--[a-z0-9-]+):(#(?:[0-9a-f]{8}|[0-9a-f]{6}));", css))
        if len(tokens) < 500:
            raise RuntimeError(f"Incomplete color capture: {len(tokens)} tokens")
        return {"tokens": tokens, "cssSha256": hashlib.sha256(css.encode()).hexdigest(),
                "requestedColorMode": mode, "requestedHighContrast": high_contrast,
                "incognito": incognito, "provider": "headless WebContents",
                "autogeneratedSeedRGB": seed,
                "userColorSource": (re.search(r"--user-color-source:([^;]+)", css).group(1)
                                    if "--user-color-source:" in css else "custom-theme")}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    result = {"schema": 1,
              "capturedAt": datetime.datetime.now(datetime.timezone.utc).isoformat(),
              "browserVersion": subprocess.check_output([CHROME, "--version"], text=True).strip(),
              "osVersion": subprocess.check_output(["sw_vers"], text=True).strip(),
              "captureMethod": "ThemeSource colors.css?sets=ui,chrome in isolated profiles",
              "variants": {}}
    for mode in ["light", "dark"]:
        result["variants"][mode] = capture(mode)
        result["variants"][f"{mode}-high-contrast"] = capture(mode, high_contrast=True)
        result["variants"][f"{mode}-incognito"] = capture(mode, incognito=True)
        result["variants"][f"{mode}-black"] = capture(mode, seed="0,0,0")
        result["variants"][f"{mode}-black-high-contrast"] = capture(
            mode, seed="0,0,0", high_contrast=True)
    args.output.write_text(json.dumps(result, sort_keys=True, indent=2) + "\n")
    print({key: len(value["tokens"]) for key, value in result["variants"].items()})
