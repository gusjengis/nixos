#!/usr/bin/env python3
"""Generate a name-keyed C++ palette from Mac Chrome's resolved color tokens."""
import argparse
import json
from pathlib import Path

VARIANTS = ("light-black", "dark-black", "light-black-high-contrast", "dark-black-high-contrast")


def generate(data):
    variants = [data["variants"][key]["tokens"] for key in VARIANTS]
    names = sorted(variants[0])
    if any(set(value) != set(names) for value in variants):
        raise ValueError("Capture variants have different token inventories")
    lines = ["// Generated by generate-macos-palette.py; do not edit.",
             "// Source: " + data["browserVersion"],
             "// Columns: light, dark, high-contrast light, high-contrast dark.",
             "// Black autogenerated theme matches the reference Mac profile.",
             "constexpr CapturedColor kCapturedColors[] = {"]
    for name in names:
        colors = []
        for values in variants:
            rgba = values[name].removeprefix("#")
            if len(rgba) != 8:
                raise ValueError(f"Expected RGBA8 for {name}: {rgba}")
            colors.append("0x" + rgba[6:8] + rgba[:6])
        lines.append('  {"' + name + '", {' + ", ".join(colors) + "}},")
    lines += ["};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("capture", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(json.loads(args.capture.read_text())))
