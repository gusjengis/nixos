import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import tarfile
import unittest

HERE = Path(__file__).parent
spec = importlib.util.spec_from_file_location("palette", HERE / "generate-macos-palette.py")
palette = importlib.util.module_from_spec(spec)
spec.loader.exec_module(palette)


class MacCaptureTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.chrome = json.loads((HERE / "chrome-colors.json").read_text())
        cls.appkit = json.loads((HERE / "appkit-theme.json").read_text())

    def test_complete_variants_and_distinct_states(self):
        variants = self.chrome["variants"]
        names = set(variants["light"]["tokens"])
        self.assertGreater(len(names), 1500)
        for variant in variants.values():
            self.assertEqual(set(variant["tokens"]), names)
            self.assertTrue(all(re.fullmatch(r"#[0-9a-f]{8}", color)
                                for color in variant["tokens"].values()))
        self.assertNotEqual(variants["light"]["tokens"], variants["dark"]["tokens"])
        self.assertNotEqual(variants["dark"]["tokens"], variants["dark-black"]["tokens"])
        self.assertNotEqual(variants["dark-black"]["tokens"],
                            variants["dark-black-high-contrast"]["tokens"])

    def test_rgba_to_argb_preserves_transparency(self):
        data = copy.deepcopy(self.chrome)
        for name in palette.VARIANTS:
            data["variants"][name]["tokens"] = {"--test-alpha": "#12345678"}
        self.assertIn('{"--test-alpha", {0x78123456, 0x78123456, 0x78123456, 0x78123456}}',
                      palette.generate(data))

    def test_reference_black_is_user_theme_not_platform_default(self):
        reference = json.loads((HERE / "reference-theme-settings.json").read_text())
        self.assertEqual(reference["autogeneratedSeedARGB"], "FF000000")
        variants = self.chrome["variants"]
        self.assertEqual(variants["dark-black"]["tokens"]["--color-frame-active"], "#000000ff")
        self.assertNotEqual(variants["dark"]["tokens"]["--color-frame-active"], "#000000ff")

    def test_incomplete_variant_rejected(self):
        data = copy.deepcopy(self.chrome)
        data["variants"][palette.VARIANTS[0]]["tokens"].popitem()
        with self.assertRaises(ValueError):
            palette.generate(data)

    def test_committed_palette_is_reproducible(self):
        self.assertEqual((HERE / "macos_palette.inc").read_text(), palette.generate(self.chrome))

    def test_appkit_capture_has_fonts_and_native_variants(self):
        self.assertEqual(len(self.appkit["appearances"]), 8)
        for appearance in self.appkit["appearances"].values():
            self.assertGreaterEqual(len(appearance["colors"]), 100)
            self.assertEqual(appearance["unresolved"], {})
        self.assertEqual(self.appkit["fonts"]["roles"]["system"]["size"], 13)
        self.assertEqual(len(self.appkit["fonts"]["weights"]), 9)
        self.assertEqual(set(self.appkit["controls"]), {"regular", "small", "mini", "large"})

    def test_archived_recipe_and_asset_hashes(self):
        with tarfile.open(HERE / "chromium-theme-sources.tar.gz") as archive:
            manifests = [entry for entry in archive.getnames() if entry.endswith("/manifest.json")]
            self.assertEqual(len(manifests), 2)
            for path in manifests:
                manifest = json.load(archive.extractfile(path))
                root = path.removesuffix("manifest.json")
                self.assertGreater(len(manifest["sources"]), 1000)
                for source, record in manifest["sources"].items():
                    actual = hashlib.sha256(archive.extractfile(root + source).read()).hexdigest()
                    self.assertEqual(actual, record["sha256"], source)
                for assets in manifest["assets"].values():
                    for asset in assets:
                        self.assertTrue(asset["path"] in manifest["sources"] or
                                        asset["path"] in manifest["unavailable"], asset["path"])


if __name__ == "__main__":
    unittest.main()
