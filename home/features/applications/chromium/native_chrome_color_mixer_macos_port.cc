namespace {

struct CapturedColor {
  std::string_view name;
  SkColor variants[4];
};

#include "chrome/browser/ui/color/macos_palette.inc"

void ApplyCapturedColor(ui::ColorMixer& mixer, ui::ColorId id,
                        std::string_view name, size_t variant) {
  const auto css_name = ui::ConvertColorProviderColorIdToCSSColorId(name);
  const auto* entry = std::lower_bound(
      std::begin(kCapturedColors), std::end(kCapturedColors), css_name,
      [](const CapturedColor& color, std::string_view key) {
        return color.name < key;
      });
  if (entry != std::end(kCapturedColors) && entry->name == css_name) {
    mixer[id] = {entry->variants[variant]};
  }
}

}  // namespace

void AddNativeChromeColorMixer(ui::ColorProvider* provider,
                               const ui::ColorProviderKey& key) {
  // Match by semantic name rather than enum number: the reference Mac and
  // Linux browser can have different Chromium versions/platform-only IDs.
  // Unknown IDs retain their upstream recipe instead of guessing a color.
  const size_t variant =
      (key.color_mode == ui::ColorProviderKey::ColorMode::kDark ? 1 : 0) +
      (key.contrast_mode == ui::ColorProviderKey::ContrastMode::kHigh ? 2 : 0);
  auto& mixer = provider->AddMixer();
  for (ui::ColorId id = ui::kUiColorsStart; id < ui::kUiColorsEnd; ++id) {
    ApplyCapturedColor(mixer, id, ui::ColorIdName(id), variant);
  }
  for (ui::ColorId id = kChromeColorsStart; id < kChromeColorsEnd; ++id) {
    ApplyCapturedColor(mixer, id, ChromeColorIdName(id), variant);
  }
  // Chrome applies extension/autogenerated theme suppliers after this mixer,
  // preserving intentional user themes and incognito's own color handling.
}
